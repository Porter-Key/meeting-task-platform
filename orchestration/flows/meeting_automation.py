def run_meeting_ingest_automation_flow(payload: dict | None = None) -> dict[str, Any]:
    payload = payload or {}
    recent_days = int(payload.get("recent_days") or 60)
    dry_run = bool(payload.get("dry_run"))
    max_attempts = int(payload.get("max_attempts") or 3)
    clients = build_application_clients()
    cleanup_stale_meeting_pipeline(clients.psql_session_factory)
    lock_service = LockService(clients.config.redis.lock_url)
    with lock_service.acquire("beat:meeting_ingest_automation", ttl_seconds=3300, metadata={"dry_run": dry_run}) as lock:
        if not lock.get("acquired"):
            logger.warning("meeting_ingest_skipped_locked", stage="orchestration", lock=lock)
            return {"status": "skipped", "reason": "locked", "lock": lock}
        flow_payload = {"recent_days": recent_days, "limit": int(payload.get("limit") or 0), "skip": int(payload.get("skip") or 0), "meeting_ids": list(payload.get("meeting_ids") or []), "from_date": payload.get("from_date"), "to_date": payload.get("to_date"), "completed_only": True}
        logger.info("meeting_ingest_started", stage="orchestration", payload=flow_payload, dry_run=dry_run)
        ingest_result = ingest_fireflies_meetings(flow_payload) if not dry_run else {"dry_run": True, "meeting_ids": []}
        processed: list[dict[str, Any]] = []
        failed: list[dict[str, Any]] = []
        meeting_ids = list(ingest_result.get("meeting_ids") or [])
        process_selection = select_unprocessed_meeting_ids(clients.psql_session_factory, meeting_ids)
        if not dry_run:
            for meeting_id in process_selection["selected_meeting_ids"]:
                processed.append(_process_meeting_with_retry(clients.psql_session_factory, lock_service, meeting_id, max_attempts=max_attempts, fallback_error=None, dry_run=dry_run, failed=failed))
        result = {"ingest": ingest_result, "process_selection": process_selection, "processed": processed, "failed": failed, "max_attempts": max_attempts, "dry_run": dry_run}
        logger.info("meeting_ingest_completed", stage="orchestration", result=result, dry_run=dry_run)
        return result


def run_meeting_ingest_and_process_flow(payload: dict | None = None) -> dict[str, Any]:
    return run_meeting_ingest_automation_flow(payload)


def select_unprocessed_meeting_ids(session_factory: Any, meeting_ids: list[str], *, force: bool = False) -> dict[str, Any]:
    """Return only meetings that lifecycle/artifacts say still need processing.

    Optimistic default: if generated artifacts exist but explicit lifecycle tags are
    missing, treat the meeting as already processed, write completion tags with a
    special skip reason, and skip it. This prevents restored historical meetings
    from being regenerated by broad recent-days automation.
    """

    unique_ids = list(dict.fromkeys(str(meeting_id) for meeting_id in meeting_ids if meeting_id))
    if not unique_ids:
        return {"selected_meeting_ids": [], "skipped_meeting_ids": [], "reasons": {}}

    selected: list[str] = []
    skipped: list[str] = []
    reasons: dict[str, dict[str, Any]] = {}
    lifecycle = LifecycleRepo(session_factory)
    with session_scope(session_factory) as session:
        for meeting_id in unique_ids:
            ingested_status = lifecycle.latest_meeting_status(meeting_id, "ingested")
            pipeline_status = lifecycle.latest_meeting_status(meeting_id, "pipeline")
            task_status = lifecycle.latest_meeting_status(meeting_id, "task_extracted")
            counts = {
                "chunks": int(session.scalar(select(func.count(MeetingChunkORM.id)).where(MeetingChunkORM.meeting_id == meeting_id)) or 0),
                "topics": int(session.scalar(select(func.count(MeetingTopicORM.id)).where(MeetingTopicORM.meeting_id == meeting_id)) or 0),
                "conclusions": int(session.scalar(select(func.count(MeetingConclusionORM.id)).where(MeetingConclusionORM.meeting_id == meeting_id)) or 0),
                "task_origins": int(session.scalar(select(func.count(TaskOriginORM.id)).where(TaskOriginORM.meeting_id == meeting_id)) or 0),
                "task_masterlist": int(session.scalar(select(func.count(TaskMasterlistORM.id)).join(TaskOriginORM, TaskMasterlistORM.origin_id == TaskOriginORM.id).where(TaskOriginORM.meeting_id == meeting_id)) or 0),
            }
            base_reason: dict[str, int | str | None] = {**counts, "ingested_status": ingested_status, "pipeline_status": pipeline_status, "task_extracted_status": task_status}
            if task_status in {"completed", "ready"} or pipeline_status == "completed":
                skipped.append(meeting_id)
                reasons[meeting_id] = {**base_reason, "reason": "already_processed"}
            elif all(counts[name] > 0 for name in ("chunks", "topics", "conclusions", "task_origins", "task_masterlist")) and not force:
                tag_metadata = {**counts, "source": "meeting_process_selection", "reason": "optimistic_artifacts_exist_without_lifecycle", "skip_policy": "optimistic_default_completed"}
                lifecycle.change_state("meeting", meeting_id, stage="task_extracted", status="completed", metadata=tag_metadata, decision=can_change_state(subject_type="meeting", stage="task_extracted", from_status=task_status, to_status="completed", metadata=tag_metadata))
                lifecycle.change_state("meeting", meeting_id, stage="pipeline", status="completed", metadata=tag_metadata, decision=can_change_state(subject_type="meeting", stage="pipeline", from_status=pipeline_status, to_status="completed", metadata=tag_metadata))
                skipped.append(meeting_id)
                reasons[meeting_id] = {**base_reason, "reason": "optimistic_artifacts_exist_without_lifecycle"}
            elif pipeline_status == "running":
                skipped.append(meeting_id)
                reasons[meeting_id] = {**base_reason, "reason": "pipeline_running"}
            elif pipeline_status == "terminal_failed" and not force:
                skipped.append(meeting_id)
                reasons[meeting_id] = {**base_reason, "reason": "terminal_failed_requires_force"}
            elif ingested_status == "ingested" or pipeline_status in {"retryable_failed", "failed_retryable"} or force:
                selected.append(meeting_id)
                reasons[meeting_id] = {**base_reason, "reason": "needs_processing"}
            else:
                skipped.append(meeting_id)
                reasons[meeting_id] = {**base_reason, "reason": "not_ingested"}
    return {"selected_meeting_ids": selected, "skipped_meeting_ids": skipped, "reasons": reasons}


def run_monday_sync_automation_flow(payload: dict | None = None) -> dict[str, Any]:
    payload = payload or {}
    dry_run = bool(payload.get("dry_run"))
    clients = build_application_clients()
    with LockService(clients.config.redis.lock_url).acquire("beat:monday_sync_automation", ttl_seconds=7100, metadata={"dry_run": dry_run}) as lock:
        if not lock.get("acquired"):
            logger.warning("monday_sync_skipped_locked", stage="orchestration", lock=lock)
            return {"status": "skipped", "reason": "locked", "lock": lock}
        logger.info("monday_sync_started", stage="orchestration", dry_run=dry_run)
        monday_users = sync_monday_users({}) if not dry_run else {"dry_run": True}
        monday_identity = associate_monday_identity({"apply": not dry_run}) if not dry_run else {"dry_run": True}
        monday_structure = sync_and_validate_monday_structure({}) if not dry_run else {"dry_run": True}
        result = {"status": "completed", "monday_users": monday_users, "monday_identity": monday_identity, "monday_structure": monday_structure}
        logger.info("monday_sync_completed", stage="orchestration", dry_run=dry_run, result=result)
        return result


def _process_meeting(session_factory: Any, lock_service: LockService, meeting_id: str) -> dict[str, Any]:
    lifecycle = LifecycleRepo(session_factory)
    with lock_service.acquire(f"meeting:{meeting_id}:pipeline", ttl_seconds=7200, metadata={"source": "meeting_ingest_automation"}) as lock:
        if not lock.get("acquired"):
            logger.warning("meeting_pipeline_skipped_locked", stage="orchestration", meeting_id=meeting_id)
            lifecycle.change_state("meeting", meeting_id, stage="pipeline", status="skipped", metadata={"reason": "locked"}, decision=can_change_state(subject_type="meeting", stage="pipeline", from_status=lifecycle.latest_meeting_status(meeting_id, "pipeline"), to_status="skipped", metadata={"reason": "locked"}))
            return {"meeting_id": meeting_id, "status": "skipped", "reason": "locked"}
        lifecycle.change_state("meeting", meeting_id, stage="pipeline", status="running", metadata={"source": "meeting_ingest_automation"}, decision=can_change_state(subject_type="meeting", stage="pipeline", from_status=lifecycle.latest_meeting_status(meeting_id, "pipeline"), to_status="running", metadata={"source": "meeting_ingest_automation"}))
        logger.info("meeting_pipeline_started", stage="orchestration", meeting_id=meeting_id)
        try:
            wash_result = wash_meeting({"meeting_id": meeting_id})
            generate_result = generate_events({"meeting_id": meeting_id, "use_existing_chunks": True, "use_ai_cleanup": False, "debug": False})
        except Exception as exc:
            cleanup_failed_generation(session_factory, meeting_id, error=exc, cleanup_half_artifacts=True)
            raise
        result = {"meeting_id": meeting_id, "status": "completed", "wash": wash_result, "generate": generate_result}
        lifecycle.change_state("meeting", meeting_id, stage="pipeline", status="completed", metadata={"generated": not bool(generate_result.get("skipped"))}, decision=can_change_state(subject_type="meeting", stage="pipeline", from_status=lifecycle.latest_meeting_status(meeting_id, "pipeline"), to_status="completed", metadata={"generated": not bool(generate_result.get("skipped"))}))
    logger.info("meeting_pipeline_completed", stage="orchestration", meeting_id=meeting_id, result=result)
    return result


def _process_meeting_with_retry(session_factory: Any, lock_service: LockService, meeting_id: str, *, max_attempts: int, fallback_error: Exception | str | None, dry_run: bool, failed: list[dict[str, Any]]) -> dict[str, Any]:
    attempts = 0
    last_error: Exception | str | None = fallback_error
    while attempts < max_attempts:
        attempts += 1
        try:
            result = {"meeting_id": meeting_id, "attempt": attempts, "result": _process_meeting(session_factory, lock_service, meeting_id)}
            return result
        except Exception as exc:
            last_error = exc
            lifecycle = LifecycleRepo(session_factory)
            decision = can_change_state(subject_type="meeting", stage="pipeline", from_status=lifecycle.latest_meeting_status(meeting_id, "pipeline"), to_status="retryable_failed", metadata={"attempt": attempts, "max_attempts": max_attempts, "error": repr(exc)})
            lifecycle.change_state("meeting", meeting_id, stage="pipeline", status="retryable_failed" if attempts < max_attempts else "terminal_failed", metadata={"attempt": attempts, "max_attempts": max_attempts}, error=repr(exc), decision=decision)
            cleanup_failed_generation(session_factory, meeting_id, error=exc, cleanup_half_artifacts=True)
            if attempts >= max_attempts:
                failed.append({"meeting_id": meeting_id, "attempts": attempts, "error": repr(exc)})
                return {"meeting_id": meeting_id, "attempts": attempts, "status": "failed", "error": repr(exc)}
    failed.append({"meeting_id": meeting_id, "attempts": attempts, "error": repr(last_error) if last_error else None})
    return {"meeting_id": meeting_id, "attempts": attempts, "status": "failed", "error": repr(last_error) if last_error else None}
